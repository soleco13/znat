// 2026-10-17: админ входит невидимкой — учитель и ученик его не видят; чат работает; «Стать видимым».
import { resetLesson, openBrowsers, P, teacherJoin, guestEnter, check, finish, sleep, waitFor, login, ORIGIN, LID, inRoom, byText, mark, openDrawer } from "./lib.mjs";
const ADMIN = "Админ Админов";
await openBrowsers(["teacher", "s1", "s2"]);
const T = P.teacher, S = P.s1, A = P.s2;
check("teacher joins", await teacherJoin(T));
await resetLesson(T);
check("student joins", await guestEnter(S, "Ученица Видимая"));
mark("админ входит невидимкой");
check("admin logs in", await login(A, "admin@school.dev"));
await A.goto(`${ORIGIN}/lessons/${LID}/room`);
const btn = await waitFor(() => A.eval(`!![...document.querySelectorAll('button')].find(b => b.textContent.includes('Войти невидимкой'))`), 40000);
check("admin sees «Войти невидимкой»", btn.ok);
await A.click(`[...document.querySelectorAll('button')].find(b => b.textContent.includes('Войти невидимкой'))`);
check("admin in room", (await waitFor(() => inRoom(A), 30000)).ok);
check("admin sees invisibility banner", (await waitFor(() => A.eval(`document.body.innerText.includes('Вы в уроке невидимо')`), 15000)).ok);
await sleep(5000);
await openDrawer(T, "Участники");
await sleep(800);
const tText = await T.eval("document.body.innerText");
const sText = await S.eval("document.body.innerText");
check("teacher does not see admin (participants panel open)", !tText.includes(ADMIN), tText.match(/Админ.{0,30}/));
check("student does not see admin", !sText.includes(ADMIN));
check("admin sees himself and others", (await A.eval("document.body.innerText")).includes("Ученица Видимая"));
const lkCount = async (p) => p.eval(`(() => { const r = window.__lkRoom; return r ? r.remoteParticipants.size : null; })()`);
check("admin has no mic/camera buttons", !(await A.eval(`[...document.querySelectorAll('button[aria-label]')].some(b => ['Микрофон','Включить звук','Камера','Включить камеру','Демонстрация'].includes(b.getAttribute('aria-label')))`)));
check("admin receives video (sees others)", (await waitFor(() => A.eval(`[...document.querySelectorAll('video')].some(v => v.videoWidth > 0)`), 20000)).ok);
mark("чат от невидимки");
await A.click(`[...document.querySelectorAll('button[aria-label]')].find(b => b.getAttribute('aria-label') === 'Чат')`);
await sleep(600);
await A.click(`document.querySelector('[aria-label="Сообщение классу"]')`);
await A.type("Привет от невидимки");
await A.click(`[...document.querySelectorAll('button[aria-label]')].find(b => b.getAttribute('aria-label') === 'Отправить')`);
await openDrawer(T, "Чат");
check("teacher gets admin chat message", (await waitFor(() => T.eval(`document.body.innerText.includes('Привет от невидимки')`), 10000)).ok);
mark("стать видимым");
await A.click(`[...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Стать видимым')`);
await openDrawer(T, "Участники");
check("teacher now sees admin", (await waitFor(() => T.eval(`document.body.innerText.split(${JSON.stringify(ADMIN)}).length - 1 >= 2`), 20000)).ok);
check("admin banner gone", (await waitFor(() => A.eval(`!document.body.innerText.includes('Вы в уроке невидимо')`), 10000)).ok);
await finish();
