// Регрессия UX-03: неотправленное сообщение остаётся в ленте с «Повторить», поле пустое, нет склейки.
import { resetLesson, openBrowsers, P, teacherJoin, guestEnter, check, finish, sleep, mark, intercept, sendChat, press, sql, openDrawer, log } from "./lib.mjs";
const btn = (t) => `[...document.querySelectorAll("button")].find(b => b.textContent.trim() === ${JSON.stringify(t)})`;
await openBrowsers(["teacher", "s1"]);
const T = P.teacher, S = P.s1;
await teacherJoin(T); await resetLesson(T);
check("s1 joins", await guestEnter(S, "Ученик Чат"));
const draft = () => S.eval(`document.querySelector('[aria-label="Сообщение классу"]').value`);
const m1 = `fail1-${Date.now() % 100000}`, m2 = `next2-${Date.now() % 100000}`;
mark("сеть отказывает — сообщение 1");
await intercept(S, [{ match: /\/chat$/, method: "POST", abort: true }]);
await sendChat(S, m1);
await sleep(2500);
check("failed: input empty", (await draft()) === "", await draft());
check("failed: shown as «Не отправлено»", await S.eval(`document.body.innerText.includes('Не отправлено') && document.body.innerText.includes(${JSON.stringify(m1)})`));
mark("набираем следующее, пока первое висит");
await S.click(`document.querySelector('[aria-label="Сообщение классу"]')`);
await S.type(m2);
await intercept(S, []);
await press(S, "Отправить");
await sleep(2000);
await S.click(btn("Повторить"));
await sleep(2500);
const r1 = await sql(`select count(*) from chat_messages where body = '${m1}'`);
const r2 = await sql(`select count(*) from chat_messages where body = '${m2}'`);
const glued = await sql(`select count(*) from chat_messages where body like '%${m1}%${m2}%' or body like '%${m2}%${m1}%'`);
check("m1 delivered once after retry", r1[0] === "1", r1);
check("m2 delivered once", r2[0] === "1", r2);
check("no glued message", glued[0] === "0", glued);
check("no «Не отправлено» left", !(await S.eval(`document.body.innerText.includes('Не отправлено')`)));
await openDrawer(T, "Чат");
await sleep(500);
{ const n = await T.eval(`[...document.querySelectorAll("body *")].filter(e => e.children.length === 0 && e.textContent.trim() === ${JSON.stringify(m1)} && !e.closest("[role=status]")).length`); check("teacher sees m1 once in chat (tile bubble excluded)", n === 1, { n }); }
mark("Удалить");
await intercept(S, [{ match: /\/chat$/, method: "POST", abort: true }]);
const m3 = `del3-${Date.now() % 100000}`;
await sendChat(S, m3); await sleep(2500);
await intercept(S, []);
await S.click(btn("Удалить")); await sleep(500);
check("deleted: gone from list", !(await S.eval(`document.body.innerText.includes(${JSON.stringify(m3)})`)));
check("deleted: not in DB", (await sql(`select count(*) from chat_messages where body = '${m3}'`))[0] === "0");
await finish();
